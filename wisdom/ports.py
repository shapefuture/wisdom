"""Frozen v1 ports. Concrete bindings belong to composition.py only."""
from __future__ import annotations
from typing import Any, Protocol

Record = dict[str, Any]

class StorePort(Protocol):
    def put(self, kind: str, data: dict, *, record_id: str | None = None,
            expected_version: int | None = None, immutable: bool = False,
            idempotency_key: str | None = None, principal: str = "local-user",
            event_type: str | None = None) -> Record: ...
    def get(self, record_id: str, version: int | None = None) -> Record: ...
    def list(self, kind: str | None = None) -> list[Record]: ...
    def history(self, record_id: str) -> list[Record]: ...
    def link(self, source_id: str, target_id: str, relation: str, *,
             polarity: str = "neutral", data: dict | None = None) -> dict: ...
    def edges(self, record_id: str | None = None) -> list[dict]: ...
    def search(self, query: str, kinds: list[str] | None = None, limit: int = 20) -> list[Record]: ...
    def append_event(self, kind: str, subject_id: str, payload: dict, *,
                     principal: str = "local-user", idempotency_key: str | None = None) -> dict: ...
    def events(self) -> list[dict]: ...
    def verify_ledger(self) -> dict: ...
    def purge_source(self, source_id: str, reason: str, *, principal: str = "local-user") -> dict: ...
    def close(self) -> None: ...

class ProposalProvider(Protocol):
    name: str
    def complete(self, operation: str, payload: dict) -> dict: ...

